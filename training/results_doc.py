"""Write docs/RESULTS.md from the logs, so the numbers in the repository and the report agree."""

from __future__ import annotations

import json
from pathlib import Path

from environment.custom_env import ENV_VERSION

ALGOS = ("dqn", "reinforce", "ppo", "a2c")
NAMES = {"dqn": "DQN", "reinforce": "REINFORCE", "ppo": "PPO", "a2c": "A2C"}


def _fmt(value) -> str:
    return f"{value:g}" if isinstance(value, float) else str(value)


def _changes(config: dict, base: dict) -> str:
    parts = [f"{key} {_fmt(value)}" for key, value in config.items() if key not in ("id", "name") and base.get(key) != value]
    return ", ".join(parts) if parts else "baseline"


def write_results(log_root: str | Path = "logs", path: str | Path = "docs/RESULTS.md") -> str:
    log_root = Path(log_root)
    evaluation_path = log_root / "test_evaluation.json"
    if not evaluation_path.exists():
        raise FileNotFoundError("run: uv run python main.py --evaluate")
    ev = json.loads(evaluation_path.read_text(encoding="utf-8"))
    lines = [
        "# Results",
        "",
        "Generated by `uv run python main.py --evaluate`. Validation deliveries are seeds 1000-1019 (used to pick each checkpoint). Test deliveries are seeds 5000-5099 and were never used for any choice.",
        "",
        "## Baselines on the test deliveries",
        "",
        "| Rider | Test return | Success | Mean minutes | Share of WAIT |",
        "| --- | --- | --- | --- | --- |",
    ]
    for key, label in (("random", "Random legal actions"), ("heuristic", "Rule-following rider")):
        b = ev["baselines"][key]
        lines.append(f"| {label} | {b['return_mean']:+.2f} (sem {b['return_sem']:.2f}) | {b['success']:.0%} | {b['minutes_mean']:.0f} | {b['wait_share']:.0%} |")
    lines += ["", "## Long runs (best setting of each algorithm)", "", "| Run | Setting | Test return | Success | Delivered | Cancelled | Share of WAIT |", "| --- | --- | --- | --- | --- | --- | --- |"]
    for key, item in sorted(ev.get("final", {}).items()):
        o = item["outcomes"]
        lines.append(f"| {key} | {item['config_name']} | {item['return_mean']:+.2f} (sem {item['return_sem']:.2f}) | {item['success']:.0%} | {o['delivered']} | {o['cancelled']} | {item['wait_share']:.0%} |")
    for algo in ALGOS:
        items = []
        for p in sorted(log_root.glob(f"{algo}/experiment_*/summary.json")):
            s = json.loads(p.read_text(encoding="utf-8"))
            if s.get("env_version") == ENV_VERSION:
                items.append(s)
        if not items:
            continue
        base = items[0]["config"]
        lines += ["", f"## {NAMES[algo]} sweep (30,000 frames, seed 0)", "", "| Exp | Setting | Change from baseline | Validation return | Test return | Test success | Share of WAIT |", "| --- | --- | --- | --- | --- | --- | --- |"]
        for s in items:
            test = ev["sweep"].get(f"{algo}_exp{s['experiment']:02d}")
            cells = [
                str(s["experiment"]),
                s["config"]["name"].replace("_", " "),
                _changes(s["config"], base),
                f"{s['best_eval_return']:+.2f}",
                f"{test['return_mean']:+.2f}" if test else "",
                f"{test['success']:.0%}" if test else "",
                f"{test['wait_share']:.0%}" if test else "",
            ]
            lines.append("| " + " | ".join(cells) + " |")
    lines += ["", "## Success rate by condition (test deliveries)", ""]
    conditions = ev["conditions"]
    names = list(conditions["heuristic"].keys())
    shown = ["heuristic"] + sorted(k for k in conditions if k.startswith(tuple(f"{a}_seed" for a in ALGOS)))
    lines.append("| Rider | " + " | ".join(names) + " |")
    lines.append("| --- | " + " | ".join("---" for _ in names) + " |")
    for key in shown:
        data = conditions[key]
        lines.append(f"| {key} | " + " | ".join(f"{data[n]['success']:.0%}" if n in data else "" for n in names) + " |")
    lines += ["", "Figures are in `logs/figures/`."]
    destination = Path(path)
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return str(destination)
